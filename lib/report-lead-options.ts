export function isDisposableEmailDomain(email: string) {
  const domain = email.split("@")[1]?.toLowerCase().replace(/\.$/, "") ?? "";
  if (!domain || domain === "localhost" || domain.endsWith(".local")) return true;
  const labels = domain.split(".");
  for (let index = 0; index < labels.length - 1; index += 1) {
    if (DISPOSABLE_DOMAINS.has(labels.slice(index).join("."))) return true;
  }
  return /(mailinator|guerrillamail|10minutemail|yopmail|trashmail|temp-mail|tempmail|sharklasers)/.test(domain);
}

export function optionValues(options: readonly { value: string }[]) {
  return new Set(options.map((item) => item.value));
}

export function reportSlugFromPath(pathname: string | null | undefined) {
  if (!pathname) return "";
  const match = /^\/reports\/([a-z0-9-]+)\/?$/.exec(pathname);
  return match?.[1] ?? "";
}
